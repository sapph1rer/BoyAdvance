    void stepOneFrame() {
        if (!hasRom) return;
        bool wasPaused = paused;
        paused = true;
        runOneFrame();
        paused = wasPaused;
    }

    void onFrameTick() {
        if (!hasRom || paused) {
            drainAudio();
            updateFpsAndTitle(false);
            frameClock.restart();
            return;
        }

        qint64 ns = frameClock.nsecsElapsed();
        frameClock.restart();
        double dt = static_cast<double>(ns) * 1e-9;
        if (dt > 0.25) dt = 0.25;
        frameAccumSec += dt * (fastForward ? fastForwardMul : 1);

        constexpr double targetFrameSec = 1.0 / 60.0;
        int maxFrames = fastForward ? (4 * fastForwardMul) : 4;
        int ran = 0;
        while (frameAccumSec >= targetFrameSec && ran < maxFrames) {
            runOneFrame();
            frameAccumSec -= targetFrameSec;
            ++ran;
        }
        if (ran == 0) {
            drainAudio();
        }
        updateFpsAndTitle(ran > 0);
        maybeAutosave();
    }

    void runOneFrame() {
        gba.runFrame();
        if (!muted) queueAudio(gba.bus.apu.consumeSamples());
        else gba.bus.apu.consumeSamples();
        debugLogFrame();
        video->setFrame(gba.bus.ppu.framebuffer());
        ++framesShown;
    }

    void updateFpsAndTitle(bool frameRan) {
        Q_UNUSED(frameRan);
        qint64 ms = fpsClock.elapsed();
        if (ms < 500) return;
        fpsValue = (framesShown * 1000.0) / static_cast<double>(ms);
        framesShown = 0;
        fpsClock.restart();
        updateWindowTitle();
    }

