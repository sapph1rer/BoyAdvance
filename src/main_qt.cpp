    void setupAudio() {
        QAudioFormat format;
        format.setSampleRate(48000);
        format.setChannelCount(2);
        format.setSampleFormat(QAudioFormat::Int16);

        QAudioDevice device = QMediaDevices::defaultAudioOutput();
        if (!device.isNull() && !device.isFormatSupported(format)) {
            statusBar()->showMessage("Audio format not supported, audio disabled.");
            audioSink = nullptr;
            audioOut = nullptr;
            addLog(emulog::Level::Warning, "AUDIO", "Audio format unsupported, audio disabled.");
            return;
        }

        if (device.isNull()) audioSink = new QAudioSink(format, this);
        else audioSink = new QAudioSink(device, format, this);
        // Keep output latency low (~40ms) to avoid delayed sound.
        audioRate = format.sampleRate();
        // Buffer sized for ~160ms: large enough to absorb multi-frame catch-up
        // bursts (onFrameTick can run up to 4 emulated frames in one tick when
        // the host lags) without truncating audio, which caused audible
        // crackling/stutter.
        const int targetBytes = std::max(4096, (audioRate * format.channelCount() * static_cast<int>(sizeof(int16_t))) / 6);
        audioSink->setBufferSize(targetBytes);
        audioOut = audioSink->start();
        gba.bus.apu.setOutputRate(format.sampleRate());
        addLog(emulog::Level::Info, "AUDIO",
               QString("Audio initialized (%1 Hz, %2 ch)")
                   .arg(format.sampleRate())
                   .arg(format.channelCount()));
    }

