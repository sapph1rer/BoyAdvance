    void saveNow(bool force) {
        if (!hasRom) return;
        if (gba.bus.backup.type() == BackupDevice::Type::None) return;
        bool ok = gba.saveSaveForROM(romPath.toStdString(), force);
        if (!ok) {
            statusBar()->showMessage("Save failed", 2500);
            addLog(emulog::Level::Error, "SAVE", "Battery save failed");
        } else if (force) {
            addLog(emulog::Level::Info, "SAVE", "Battery save flushed");
        }
    }

    void onLoadROM() {
        QString rom = QFileDialog::getOpenFileName(this, "Load ROM", QString(), "GBA ROM (*.gba);;All files (*.*)");
        if (rom.isEmpty()) return;
        loadROM(rom, true);
    }

    void onLoadBIOS() {
        QString bios = QFileDialog::getOpenFileName(this, "Load BIOS", QString(), "GBA BIOS (*.bin);;All files (*.*)");
        if (bios.isEmpty()) return;
        if (!loadBIOS(bios)) {
            QMessageBox::warning(this, "BIOS", "Failed to load BIOS.");
        }
    }

    void refreshRecentMenu() {
        recentMenu->clear();
        if (recentRoms.isEmpty()) {
            QAction* empty = recentMenu->addAction("(empty)");
            empty->setEnabled(false);
            return;
        }
        for (const QString& p : recentRoms) {
            QAction* a = recentMenu->addAction(p);
            connect(a, &QAction::triggered, this, [this, p]() { loadROM(p, false); });
        }
    }

    void openSaveFolder() {
        QString folder;
        if (hasRom) {
            QFileInfo fi(batterySavePath());
            folder = fi.absolutePath();
        } else {
            folder = QDir::currentPath();
        }
        QDesktopServices::openUrl(QUrl::fromLocalFile(folder));
    }

    void showRomInfo() {
        if (!hasRom) {
            QMessageBox::information(this, "ROM info", "No ROM loaded.");
            return;
        }
        QString info = QString("ROM: %1\nSize: %2 KB\nSave type: %3\nBIOS loaded: %4")
                           .arg(romPath)
                           .arg(gba.bus.cart.data().size() / 1024)
                           .arg(QString::fromStdString(gba.bus.backup.typeName()))
                           .arg(gba.bus.bios.loaded() ? "Yes" : "No");
        QMessageBox::information(this, "ROM info", info);
    }

    void openLogViewer() {
        if (logViewer) {
            logViewer->show();
            logViewer->raise();
            logViewer->activateWindow();
            return;
        }
        logViewer = new LogViewerDialog(this);
        logViewer->setAttribute(Qt::WA_DeleteOnClose, true);
        connect(logViewer, &QObject::destroyed, this, [this]() { logViewer = nullptr; });
        logViewer->show();
    }

    void openDebugSettings() {
        DebugSettingsDialog dlg(this);
        if (dlg.exec() != QDialog::Accepted) return;
        dlg.applyToSettings();
        if (actionDebugMode) actionDebugMode->setChecked(emudebug::Settings::instance().isEnabled());
        addLog(emulog::Level::Info, "DEBUG", "Updated debug settings");
    }

    void debugLogFrame() {
        const auto& dbg = emudebug::Settings::instance();
        if (!dbg.isEnabled()) return;
        ++debugFrameCounter;
        const int interval = std::max(1, dbg.getFrameInterval());
        if ((debugFrameCounter % interval) != 0) return;
        const uint32_t domains = dbg.getDomains();

        if (domains & emudebug::CPU) {
            std::ostringstream ss;
            ss << "pc=0x" << std::hex << gba.cpu.pc()
               << " cpsr=0x" << gba.cpu.cpsrValue()
               << " halt=" << std::dec << (gba.bus.haltMode ? 1 : 0)
               << " IE=0x" << std::hex << gba.bus.irq.IE
               << " IF=0x" << gba.bus.irq.IF
               << " IME=0x" << gba.bus.irq.IME
               << " keyinput=0x" << gba.bus.keypad.keyinput();
            addLog(emulog::Level::Debug, "CPU", QString::fromStdString(ss.str()));
        }
        if (domains & emudebug::GPU) {
            std::ostringstream ss;
            ss << "mode=" << (gba.bus.ppu.dispcnt & 7)
               << " vcount=" << gba.bus.ppu.vcount
               << " dispcnt=0x" << std::hex << gba.bus.ppu.dispcnt
               << " dispstat=0x" << gba.bus.ppu.dispstat
               << " bldcnt=0x" << gba.bus.ppu.bldcnt
               << " bldalpha=0x" << gba.bus.ppu.bldalpha;
            addLog(emulog::Level::Debug, "GPU", QString::fromStdString(ss.str()));
        }
        if (domains & emudebug::DMA) {
            std::ostringstream all;
            bool any = false;
            for (int i = 0; i < 4; ++i) {
                const auto& c = gba.bus.dma.ch[i];
                if (!c.active) continue;
                any = true;
                all << "ch" << i
                    << "(t=" << ((c.control >> 12) & 0x3)
                    << " rem=0x" << std::hex << c.internalCount
                    << " src=0x" << c.internalSrc
                    << " dst=0x" << c.internalDst
                    << std::dec << ") ";
            }
            if (any) addLog(emulog::Level::Debug, "DMA", QString::fromStdString(all.str()));
        }
        if ((domains & emudebug::RAM) && (debugFrameCounter % (interval * 20) == 0)) {
            uint32_t ew = 0;
            uint32_t iw = 0;
            for (size_t i = 0; i < 64; ++i) ew = (ew * 16777619u) ^ gba.bus.ewram[i];
            for (size_t i = 0; i < 64; ++i) iw = (iw * 16777619u) ^ gba.bus.iwram[i];
            std::ostringstream ss;
            ss << "ewram_hash=0x" << std::hex << ew
               << " iwram_hash=0x" << iw
               << " sp=0x" << gba.cpu.rawReg(13);
            addLog(emulog::Level::Debug, "RAM", QString::fromStdString(ss.str()));
        }
    }

