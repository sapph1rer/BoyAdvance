int main(int argc, char** argv) {
    QCoreApplication::setOrganizationName("GbaEmuProject");
    QCoreApplication::setApplicationName("GbaEmuQt");

    CliOptions opts = parseArgs(argc, argv);
    if (opts.help) {
        printUsage(argv[0]);
        return 0;
    }
    if (!opts.error.empty()) {
        std::cerr << "Error: " << opts.error << "\n\n";
        printUsage(argv[0], std::cerr);
        return 1;
    }

    // Keep startup clean in GUI mode while allowing user override via env var.
    if (qEnvironmentVariableIsEmpty("QT_LOGGING_RULES")) {
        qputenv("QT_LOGGING_RULES", QByteArray("qt.multimedia.ffmpeg.*=false"));
    }

    QApplication app(argc, argv);
    EmuMainWindow window(opts.scale);
    window.applyCli(opts);
    window.show();
    return app.exec();
}
