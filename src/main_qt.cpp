    bool loadROM(const QString& path, bool addRecent) {
        if (path.isEmpty()) return false;
        if (hasRom) saveNow(true);
        if (!fs::exists(path.toStdString())) {
            QMessageBox::warning(this, "ROM", "ROM file not found.");
            addLog(emulog::Level::Error, "ROM", QString("ROM not found: %1").arg(path));
            return false;
        }
        if (!gba.loadROM(path.toStdString())) {
            QMessageBox::warning(this, "ROM", "Failed to load ROM.");
            addLog(emulog::Level::Error, "ROM", QString("Failed to load ROM: %1").arg(path));
            return false;
        }
        if (!gba.configureBackupFromROM()) {
            QMessageBox::warning(this, "ROM", "Failed to configure backup device.");
            addLog(emulog::Level::Error, "SAVE", "Failed to configure backup device.");
            return false;
        }
        if (gba.bus.backup.type() != BackupDevice::Type::None) {
            gba.loadSaveForROM(path.toStdString());
        }

        bool wantRunBios = actionBootBIOS && actionBootBIOS->isChecked();
        if (wantRunBios && !gba.bus.bios.loaded()) {
            tryAutoLoadDefaultBIOS();
        }
        bool skipBios = true;
        if (wantRunBios && gba.bus.bios.loaded()) skipBios = false;
        gba.reset(skipBios);

        romPath = path;
        romName = QFileInfo(path).completeBaseName();
        hasRom = true;
        paused = false;
        actionPause->setChecked(false);
        framesShown = 0;
        fpsValue = 0.0;
        fpsClock.restart();
        frameClock.restart();
        frameAccumSec = 0.0;
        autosaveClock.restart();
        debugFrameCounter = 0;
        pendingAudio.clear();
        statusBar()->showMessage(QString("Loaded ROM: %1 | Save: %2")
                                     .arg(romName)
                                     .arg(QString::fromStdString(gba.bus.backup.typeName())),
                                 5000);
        addLog(emulog::Level::Info, "ROM",
               QString("Loaded ROM: %1 (save=%2)")
                   .arg(path)
                   .arg(QString::fromStdString(gba.bus.backup.typeName())));
        if (emudebug::Settings::instance().enabledFor(emudebug::ROM)) {
            const auto& rom = gba.bus.cart.data();
            if (rom.size() >= 0xB0) {
                QByteArray titleRaw(reinterpret_cast<const char*>(&rom[0xA0]), 12);
                QByteArray gameRaw(reinterpret_cast<const char*>(&rom[0xAC]), 4);
                addLog(emulog::Level::Debug, "ROM",
                       QString("header title='%1' code='%2'")
                           .arg(QString::fromLatin1(titleRaw).trimmed())
                           .arg(QString::fromLatin1(gameRaw)));
            }
        }

        if (addRecent) {
            recentRoms.removeAll(path);
            recentRoms.prepend(path);
            while (recentRoms.size() > 10) recentRoms.removeLast();
            refreshRecentMenu();
        }
        video->setFocus(Qt::OtherFocusReason);
        updateWindowTitle();
        return true;
    }

